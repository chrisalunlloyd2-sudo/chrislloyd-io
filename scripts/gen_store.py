def write_page(cats, items):
    e = html.escape
    panel, sections = [], []
    for c in cats:
        its = [i for i in items if i["category"] == c]
        if not its: continue
        panel.append(f'      <li><a href="#{slug(c)}" data-cat="{slug(c)}" aria-current="false">{e(c)} <span>{len(its)}</span></a></li>')
        cards = []
        for i in its:
            feats = "".join(f"<li>{e(f)}</li>" for f in i["features"])
            im = f'<img src="{e(img(i["image"]))}" alt="{e(i["title"])}" loading="lazy" width="240" height="240">' if i["image"] else ""
            cards.append(f'<article class="card product">{im}<h3>{e(i["title"])}</h3><p>{e(i["desc"])}</p>' +
                         (f'<ul class="features">{feats}</ul>' if feats else "") +
                         f'<a href="{e(i["url"])}" target="_blank" rel="noopener noreferrer sponsored">View in store</a></article>')
        sections.append(f'<section class="cat" id="{slug(c)}" data-cat="{slug(c)}"><h2>{e(c)}</h2><div class="grid">' + "".join(cards) + "</div></section>")
    page = PAGE.replace("{total}", str(len(items))).replace("{panel}", "\n".join(panel)).replace("{sections}", "\n".join(sections))
    open(os.path.join(ROOT, "products.html"), "w", encoding="utf-8").write(page)

def main(snap):
    cur = json.load(open(os.path.join(ROOT, "data/store-curation.json"), encoding="utf-8"))
    prods = {p["handle"]: p for p in json.load(open(snap, encoding="utf-8"))["products"]}
    base = cur["store_base"]
    out = []
    for it in cur["items"]:
        p = prods.get(it["handle"])
        if not p:
            print("MISSING handle:", it["handle"][:50], file=sys.stderr); continue
        short, feats = parse(p.get("body_html"))
        out.append({
            "id": it["handle"][:40], "title": it["title"], "category": it["category"],
            "desc": short, "features": feats,
            "image": fetch_image(it["handle"][:40], p["images"][0]["src"] if p.get("images") else ""),
            "url": f"{base}/products/{it['handle']}",
        })
    json.dump({"categories": cur["categories"], "items": out},
              open(os.path.join(ROOT, "data/store.json"), "w", encoding="utf-8"), indent=2, ensure_ascii=False)
    write_page(cur["categories"], out)
    print(len(out), "products written")

if __name__ == "__main__":
    main(sys.argv[1])
