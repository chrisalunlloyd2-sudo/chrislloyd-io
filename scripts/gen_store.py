"""Build data/store.json + products.html from the store's public products.json.

Usage: python3 scripts/gen_store.py <products.json snapshot>
Everything in stock in the store is listed. Categories come from data/store-rules.json; data/store-curation.json only holds optional per-product overrides (title, category, hidden, title_only).
Deterministic: text is only stripped/truncated from the store's own listing, never written.
"""
import hashlib, html, json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
