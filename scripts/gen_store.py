def price_fields(p):
    prices = sorted({float(v["price"]) for v in p.get("variants", []) if v.get("price")})
    if not prices:
        return {}
    return {"price": "%.2f" % prices[0], "price_from": len(prices) > 1 and prices[-1] > prices[0]}

def write_page(cats, items):
    e = html.escape
    panel, sections = [], []
    for c in cats:
        its = [i for i in items if i["category"] == c]
        if not its: continue
        panel.append(f'      <li><a href="#{slug(c)}" data-cat="{slug(c)}" aria-current="false"><span class="lbl">{e(c)}</span> <span>{len(its)}</span></a></li>')
        cards = []
        for i in its:
            feats = "".join(f"<li>{e(f)}</li>" for f in i["features"])
            im = (f'<span class="pimg"><img src="{e(img(i["image"]))}" alt="" loading="lazy" width="240" height="240"></span>'
                  if i["image"] else "")
            cards.append(f'<article class="card product">{im}<div class="pbody">'
                         f'<h3><a href="{e(i["url"])}" target="_blank" rel="noopener noreferrer sponsored">{e(i["title"])}</a></h3>'
                         + (f'<p class="pprice">' + ('<span class="pfrom">From</span> ' if i.get("price_from") else '') +
                          f'<span class="amt" data-no-i18n data-usd="{e(i["price"])}">US${e(i["price"])}</span></p>' if i.get("price") else "") +
                         f'<p>{e(i["desc"])}</p>' +
                         (f'<ul class="features">{feats}</ul>' if feats else "") +
                         '<span class="pcta">View in store</span></div></article>')
        sections.append(f'<section class="cat" id="{slug(c)}" data-cat="{slug(c)}"><h2>{e(c)}</h2><div class="grid">' + "".join(cards) + "</div></section>")
    page = PAGE.replace("{total}", str(len(items))).replace("{panel}", "\n".join(panel)).replace("{sections}", "\n".join(sections)).replace("{nav}", sitechrome.nav("store")).replace("{mbar}", sitechrome.mbar()).replace("{ping}", sitechrome.PING_NOTE)
    open(os.path.join(ROOT, "products.html"), "w", encoding="utf-8").write(page)

def auto_title(t):
    t = clean(t)
    t = re.sub(r"(?i)\bbest.?sellers?\b|\b\d(\.\d)? stars?\b", "", t)
    t = re.sub(r"(?<=\w)'S\b", "'s", t)
    t = " ".join(t.split())
    if len(t) <= 70:
        return t
    cut = re.match(r"^(.{25,70}?)(?:,|\s[-|]\s)", t)
    t = cut.group(1).strip() if cut else t[:70].rsplit(" ", 1)[0]
    return re.sub(r"(?i)(?:[\s,;:-]+(?:with|and|for|to|of|the|a|in|&))+$", "", t).rstrip(",;:- ")

def categorize(p, rules):
    hay = " ".join([p.get("title") or "", p.get("product_type") or "", " ".join(p.get("tags") or [])]).lower()
    for c in rules["categories"]:
        if any(re.search(pat, hay) for pat in c["patterns"]):
            return c["name"]
    return rules["default"]

def image_ids(handles):
    ids, used = {}, set()
    for h in handles:
        i = h[:40]
        if i in used:
            i = h[:32] + "-" + hashlib.md5(h.encode()).hexdigest()[:6]
        used.add(i); ids[h] = i
    return ids

def in_stock(p):
    return any(v.get("available") for v in p.get("variants", []))

def build_items(feed, cur, rules):
    ov = cur.get("overrides", {})
    prods = [p for p in feed if in_stock(p) and not re.match(r"(?i)^example product", p["title"]) and not ov.get(p["handle"], {}).get("hidden")]
    ids = image_ids(sorted(p["handle"] for p in prods))
    order = [c["name"] for c in rules["categories"]] + [rules["default"]]
    out = []
    for p in prods:
        o = ov.get(p["handle"], {})
        short, feats = parse(p.get("body_html"))
        if o.get("title_only"): short, feats = "", []
        title = o.get("title") or auto_title(p["title"])
        head = clean(p["title"]).lower()[:30]
        if short.lower().startswith(head): short = ""
        feats = [f for f in feats if not f.lower().startswith(head)]
        out.append({
            "id": ids[p["handle"]], "title": title, "category": o.get("category") or categorize(p, rules),
            "desc": short or title, "features": feats,
            "image": fetch_image(ids[p["handle"]], p["images"][0]["src"] if p.get("images") else ""),
            "url": f"{cur['store_base']}/products/{p['handle']}",
            **price_fields(p),
        })
    out.sort(key=lambda i: (order.index(i["category"]), i["title"].lower(), i["url"]))
    return order, out

def main(snap):
    cur = json.load(open(os.path.join(ROOT, "data/store-curation.json"), encoding="utf-8"))
    rules = json.load(open(os.path.join(ROOT, "data/store-rules.json"), encoding="utf-8"))
    feed = json.load(open(snap, encoding="utf-8"))["products"]
    order, out = build_items(feed, cur, rules)
    json.dump({"categories": order, "items": out},
              open(os.path.join(ROOT, "data/store.json"), "w", encoding="utf-8"), indent=2, ensure_ascii=False)
    write_page(order, out)
    print(len(out), "products written")

if __name__ == "__main__":
    main(sys.argv[1])
