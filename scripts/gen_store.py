#!/usr/bin/env python3
"""Build data/store.json + products.html from the store's public products.json.

Usage: python3 scripts/gen_store.py <products.json snapshot>
Curation lives in data/store-curation.json (add a handle there to add a product).
Deterministic: text is only stripped/truncated from the store's own listing, never written.
"""
import html, json, os, re, sys
from html.parser import HTMLParser

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

class Strip(HTMLParser):
    def __init__(self):
        super().__init__(); self.lis = []; self.text = []; self._li = None
    def handle_starttag(self, t, a):
        if t == "li": self._li = []
        if t in ("br", "p", "div"): self.text.append(" ")
    def handle_endtag(self, t):
        if t == "li" and self._li is not None:
            s = " ".join("".join(self._li).split())
            if s: self.lis.append(s)
            self._li = None
    def handle_data(self, d):
        self.text.append(d)
        if self._li is not None: self._li.append(d)

EMOJI = re.compile("[\U0001F000-\U0001FAFF\u2600-\u27BF\uFE0F\u200d]")
JUNK = re.compile(r"as shown in|variation|healthier|\bcures?\b|medical|1 x |^s: |^l: |warranty|in this link|\bfaq\b|is it possible|how about|please note|contact us|please order|love it|absolutely|highly recommend|great product|mission statement|five stars|5 stars|surprised with|obsessed with|exactly what i wanted|sleep at ease", re.I)
LEAD = re.compile(r"^(product description|key features|features)\s*:?\s*", re.I)

def clean(s):
    s = EMOJI.sub("", s).replace("&amp;", "&")
    s = " ".join(s.split())
    return LEAD.sub("", s).strip(" |-:")

def clip(s, n):
    s = clean(s)
    if len(s) <= n: return s
    cut = s[:n].rsplit(" ", 1)[0].rstrip(",;:- ")
    return cut + "…"

def label_case(s):
    m = re.match(r"^([A-Z0-9 .,!&'-]{4,40}):\s*(.*)$", s)
    return (m.group(1).title() + ": " + m.group(2)) if m else s

def sentences(text):
    return [x for x in re.split(r"(?<=[.!?])\s+", text) if len(x) > 12]

def parse(body):
    p = Strip(); p.feed(body or "")
    text = clean(" ".join(p.text))
    lis = [clean(x) for x in p.lis]
    if not lis:
        lis = [clean(x) for x in re.split(r"\s\d\.\s", " " + text) if len(clean(x)) > 12]
        if len(lis) < 3:
            lis = sentences(text)[1:]
    feats, seen = [], set()
    for x in lis:
        x = clip(label_case(x), 140)
        if len(x) < 9 or "?" in x or JUNK.search(x) or x.lower() in seen: continue
        seen.add(x.lower()); feats.append(x)
        if len(feats) == 6: break
    ss = [x for x in sentences(text) if not JUNK.search(x)]
    first = ss[0] if ss else text
    if re.match(r"^1\.", first): first = re.sub(r"^1\.\s*", "", first)
    first = re.split(r"\s[\u2013\u2014]\s", first)[0]
    first = re.sub(r"^[^:]{3,40}:\s+(?=\S{3})", "", first)
    first = re.sub(r"\s\d\.$", ".", first)
    return clip(first, 120), feats

def slug(c): return re.sub(r"[^a-z0-9]+", "-", c.lower()).strip("-")
def img(u, w=480):
    if not u or not u.startswith("http"): return u
    return u + ("&" if "?" in u else "?") + f"width={w}"

def fetch_image(pid, remote):
    if not remote: return ""
    d = os.path.join(ROOT, "assets", "store"); os.makedirs(d, exist_ok=True)
    rel = f"assets/store/{pid}.jpg"
    dest = os.path.join(ROOT, rel)
    if os.path.exists(dest) and os.path.getsize(dest) > 1000: return rel
    try:
        import urllib.request
        data = urllib.request.urlopen(urllib.request.Request(img(remote), headers={"User-Agent": "Mozilla/5.0"}), timeout=30).read()
        if len(data) < 1000: raise ValueError("too small")
        open(dest, "wb").write(data)
        return rel
    except Exception as ex:
        print("image download failed, keeping remote link:", pid, ex, file=sys.stderr)
        return remote

